#!/usr/bin/env python3
"""Phase 0 -- dataset integrity. Run this before anything else.

Checks Finebadminton-20K against FBBench (rule 2), writes the match split
(rule 3) to configs/split_20k.json, and rewrites the 20K section of
results/dataset_report.md between its markers. The FBBench sections above the
markers are maintained by hand.

Needs only the annotations (~26 MB), not the 43 GB of video:
    hf download Moujuruo/Finebadminton-20K --repo-type dataset \\
        --include "finebadminton-20K/*.json" "*.txt" --local-dir data/fb20k
"""
import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))

from bavlm.data.splits import (benchmark_videos, check_overlap, is_clean_label,  # noqa: E402
                               label_vocabulary, load_rallies, match_split)

BEGIN, END = "<!-- 20k:begin -->", "<!-- 20k:end -->"


def _vocab_md(vocab) -> str:
    out = []
    for name, counts in vocab.items():
        clean = [(k, n) for k, n in counts.most_common() if is_clean_label(k) or isinstance(k, int)]
        noise = [(k, n) for k, n in counts.most_common() if (k, n) not in clean]
        out.append(f"**{name}**: {len(clean)} values"
                   + (f" (+ {sum(n for _, n in noise)} noisy entries: "
                      + ", ".join(f"`{k!r}` {n}" for k, n in noise) + ")" if noise else "") + "\n")
        out.append(" · ".join(f"{k} {n:,}" for k, n in clean) + "\n")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--train", default="data/fb20k")
    ap.add_argument("--revision", default="72cae601e08c83ee8ec7e19f8fd7850e9158af7d")
    ap.add_argument("--report", default="results/dataset_report.md")
    ap.add_argument("--split", default="configs/split_20k.json")
    ap.add_argument("--val-matches", type=int, default=5)
    a = ap.parse_args()

    if not (pathlib.Path(a.train) / "benchmark_source_videos.txt").exists():
        print(__doc__)
        return 1

    rallies, bench = load_rallies(a.train), benchmark_videos(a.train)
    rep = check_overlap(a.train)
    split = match_split(rallies, bench, val_matches=a.val_matches, seed=0)
    vocab = label_vocabulary(rallies)
    fps = {}
    for r in rallies:
        fps[round(r.fps)] = fps.get(round(r.fps), 0) + 1
    secs = sum(r.seconds for r in rallies) / len(rallies)

    matches = {k: sorted({r.video for r in v}) for k, v in split.items()}
    matches["held_out_fbbench"] = sorted(bench)
    pathlib.Path(a.split).write_text(json.dumps(
        {"revision": a.revision, "rule": "split by match; FBBench source matches held out",
         "seed": 0, **matches}, indent=1) + "\n")

    sec = f"""{BEGIN}
## Finebadminton-20K — `Moujuruo/Finebadminton-20K`

Generated by `scripts/00_verify_dataset.py`; do not edit by hand.

| | |
|---|---|
| HF revision | `{a.revision}` |
| Contents | {rep['videos']} full-match videos (43.4 GB) · one annotation JSON per match (26 MB) |
| Rallies / hits | **{rep['rallies']:,}** rallies · **{sum(len(r.hits) for r in rallies):,}** hits (the full dataset has 3,215 / 33,325) |
| Mean rally | {secs:.1f} s |
| Frame rate | **not constant**: {", ".join(f"~{k} fps × {n:,} rallies" for k, n in sorted(fps.items(), reverse=True))}. Convert frame indices with each rally's own `fps` |
| Rally key | `video` + `start_frame`–`end_frame` (no clip IDs) |

## Rule 2 — overlap check: clean, by holding out FBBench's matches

FBBench clips are renamed `video_NNNNNN` and carry no source video or frame
range, so comparing IDs reports zero overlap whatever the truth (the original
`check_overlap` did exactly that). The 20K release publishes
`benchmark_source_videos.txt`: the **{rep['bench_videos']} match videos FBBench was built from**,
all {rep['bench_videos_in_20k']} present in this release.

**Every rally from those {rep['bench_videos']} matches is held out of training** ({rep['held_out_rallies']} rallies,
{100 * rep['held_out_rallies'] / rep['rallies']:.0f}%). What remains cannot contain an FBBench rally, provided the
publisher's list is complete. Training uses only the other {rep['train_videos']} matches.

| Split (by match, rule 3, seed 0) | Matches | Rallies |
|---|---|---|
| train | {len(matches['train'])} | {len(split['train']):,} |
| val | {len(matches['val'])} | {len(split['val']):,} |
| held out (FBBench source) | {rep['bench_videos']} | {rep['held_out_rallies']:,} |

The split is fixed in `configs/split_20k.json`. Val matches: {", ".join(m.removesuffix('.mp4') for m in matches['val'])}.

**Residual risk:** the result rests on the publisher's list. Before
fine-tuning, a frame-fingerprint spot check (perceptual hash of FBBench clip
frames against the {rep['train_videos']} training matches) would confirm it independently.
That needs the training videos, so it is a phase-2 task on Kaggle.

## Label vocabulary (every hit, all {rep['videos']} matches)

{_vocab_md(vocab)}
The paper's counts hold: **11 hit types, 20 subtypes, 9 court regions**,
quality 1–7. The release adds a few blank, Chinese or punctuation labels
(listed above); they are flagged by `is_clean_label`, never remapped. Quality
is stored as both `4` and `"4"`; `label_vocabulary` merges them.
{END}"""

    report = pathlib.Path(a.report)
    text = report.read_text(encoding="utf-8")
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + sec + text[text.index(END) + len(END):]
    else:
        text = text.rstrip("\n") + "\n\n---\n\n" + sec + "\n"
    report.write_bytes(text.encode())
    print(f"wrote {a.report} and {a.split}")
    print(json.dumps(rep, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
